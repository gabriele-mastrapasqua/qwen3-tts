#!/usr/bin/env python3
"""Emit src/iq_tables.inc — the IQ codebooks, extracted from llama.cpp's own
`gguf` package rather than transcribed by hand.

This matters. The IQ family does not compute its values from a formula: each
type indexes a hand-trained lookup grid of 256 to 2048 entries. Typing those
out from memory or from a screenshot is how you get a decoder that returns
plausible numbers and wrong ones — the exact failure this library keeps warning
about, and the reason IQ support was held back until this script existed.

Everything here is derived, and tools/gen_reference.py then checks the C
decoders against the same package's dequantizer.

Usage (any interpreter that has `gguf` installed):
    python3 tools/gen_iq_tables.py
    /path/to/venv/bin/python tools/gen_iq_tables.py
"""

from __future__ import annotations

import os
import sys

try:
    import numpy as np
    from gguf import quants
except ImportError:
    sys.exit("needs the `gguf` package: pip install gguf  (or use a venv that has it)")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# IQ1_S and IQ1_M share one grid, so it is emitted once.
GRIDS = [
    ("IQ1_S",   "ingot_iq1s_grid"),
    ("IQ2_XXS", "ingot_iq2xxs_grid"),
    ("IQ2_XS",  "ingot_iq2xs_grid"),
    ("IQ2_S",   "ingot_iq2s_grid"),
    ("IQ3_XXS", "ingot_iq3xxs_grid"),
    ("IQ3_S",   "ingot_iq3s_grid"),
]


def emit_int8(out, name: str, values, per_line: int = 16, comment: str = "") -> None:
    out.append(f"/* {comment} */" if comment else "")
    out.append(f"static const int8_t {name}[{len(values)}] = {{")
    for i in range(0, len(values), per_line):
        chunk = ", ".join(f"{int(v):4d}" for v in values[i:i + per_line])
        out.append(f"    {chunk},")
    out.append("};")
    out.append("")


def main() -> int:
    out: list[str] = [
        "/* GENERATED by tools/gen_iq_tables.py from llama.cpp's `gguf` package.",
        " * Do not edit: regenerate instead. See the script for why these are",
        " * extracted rather than typed.",
        " * SPDX-License-Identifier: MIT */",
        "",
    ]

    for type_name, c_name in GRIDS:
        cls = getattr(quants, type_name)
        cls.init_grid()
        grid = np.asarray(cls.grid).reshape(-1)
        assert np.all(grid == np.round(grid)), type_name
        assert grid.min() >= -128 and grid.max() <= 127, type_name
        rows, cols = cls.grid_shape
        emit_int8(out, c_name, grid.astype(np.int64).tolist(),
                  comment=f"{type_name}: {rows} entries x {cols} values, "
                          f"map {tuple(cls.grid_map)}")
        out.append(f"#define {c_name.upper()}_ENTRIES {rows}")
        out.append(f"#define {c_name.upper()}_WIDTH   {cols}")
        out.append("")

    # The shared sign table: 128 entries, one per 7-bit sign index. Bit i of
    # entry k says whether value i of the group is negated.
    ksigns = np.frombuffer(quants.IQ2_XXS.ksigns, dtype=np.uint8)
    assert len(ksigns) == 128
    out.append("/* Shared 7-bit sign codebook (IQ2_XXS, IQ3_XXS): bit i of entry k")
    out.append(" * negates value i of the 8-wide group. */")
    out.append(f"static const uint8_t ingot_iq_ksigns[{len(ksigns)}] = {{")
    for i in range(0, len(ksigns), 16):
        out.append("    " + ", ".join(f"0x{v:02x}" for v in ksigns[i:i + 16]) + ",")
    out.append("};")
    out.append("")

    # IQ4_NL's 16 non-linear levels, kept here so every codebook lives in one
    # generated place even though this one is short enough to read.
    emit_int8(out, "ingot_iq4nl_values", list(quants.IQ4_NL.kvalues),
              comment="IQ4_NL / IQ4_XS: 16 non-linear levels")

    path = os.path.join(ROOT, "src", "iq_tables.inc")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    size = os.path.getsize(path)
    print(f"src/iq_tables.inc  {len(out)} lines, {size / 1024:.0f} KiB of source")
    return 0


if __name__ == "__main__":
    sys.exit(main())
